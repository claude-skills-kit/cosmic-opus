function julianCenturies(date){ return (date.getTime()/86400000 + 2440587.5 - 2451545.0) / 36525; }
const D2R = Math.PI/180;
function heliocentric(el, T){
  const a = el.a[0] + el.a[1]*T, e = el.e[0] + el.e[1]*T;
  const I = (el.i[0] + el.i[1]*T)*D2R;
  const L = (el.L[0] + el.L[1]*T)*D2R;
  const w = (el.w[0] + el.w[1]*T)*D2R;
  const O = (el.O[0] + el.O[1]*T)*D2R;
  const wArg = w - O;
  let M = L - w; M = ((M % (2*Math.PI)) + 2*Math.PI) % (2*Math.PI);
  let E = M;
  for (let k=0;k<6;k++) E = E - (E - e*Math.sin(E) - M)/(1 - e*Math.cos(E));
  const xv = a*(Math.cos(E) - e), yv = a*Math.sqrt(1-e*e)*Math.sin(E);
  const cw = Math.cos(wArg), sw = Math.sin(wArg), cO = Math.cos(O), sO = Math.sin(O), cI = Math.cos(I), sI = Math.sin(I);
  const x = (cw*cO - sw*sO*cI)*xv + (-sw*cO - cw*sO*cI)*yv;
  const y = (cw*sO + sw*cO*cI)*xv + (-sw*sO + cw*cO*cI)*yv;
  const z = (sw*sI)*xv + (cw*sI)*yv;
  return {x, y, z, a, e, I, E};
}
function orbitPath(el, T, n){
  const pts = [], a = el.a[0]+el.a[1]*T, e = el.e[0]+el.e[1]*T;
  const I=(el.i[0]+el.i[1]*T)*D2R, w=(el.w[0]+el.w[1]*T)*D2R, O=(el.O[0]+el.O[1]*T)*D2R, wArg=w-O;
  const cw=Math.cos(wArg), sw=Math.sin(wArg), cO=Math.cos(O), sO=Math.sin(O), cI=Math.cos(I), sI=Math.sin(I);
  for (let k=0;k<=n;k++){
    const E = k/n*2*Math.PI;
    const xv=a*(Math.cos(E)-e), yv=a*Math.sqrt(1-e*e)*Math.sin(E);
    pts.push({
      x:(cw*cO-sw*sO*cI)*xv + (-sw*cO-cw*sO*cI)*yv,
      y:(cw*sO+sw*cO*cI)*xv + (-sw*sO+cw*cO*cI)*yv,
      z:(sw*sI)*xv + (cw*sI)*yv});
  }
  return pts;
}
function periodYears(a){ return Math.sqrt(a*a*a); }

